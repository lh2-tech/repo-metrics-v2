#!/usr/bin/env python3
"""Collect due-diligence metrics for a list of GitHub / GitLab / local repos.

Metrics produced per repo
-------------------------
1. logical_loc            scc Code column, whole repo
2. non_authored_loc       logical_loc - authored_loc, where authored_loc excludes
                          vendored directories, generated files and minified files
3. duplication_ratio      jscpd percentage / 100 (built-in fallback if jscpd absent)
4. non_merge_commits      git log --no-merges, revert subjects dropped
5. build_test_status      "Builds + test suite passes" / "Builds only" / "Not verified"
                          plus build command and runtime version

Usage
-----
    python3 repo_metrics.py --repos repos.txt --out outputs/run1

    # with real build attempts inside Docker
    python3 repo_metrics.py --repos repos.txt --out outputs/run1 --build-check docker

Input file accepts, one per line (blank lines and # comments ignored):
    owner/repo                          -> GitHub
    https://github.com/owner/repo       -> GitHub
    https://gitlab.com/group/sub/repo   -> GitLab
    git@github.com:owner/repo.git
    /abs/path/to/local/clone
A CSV with a `full_name`, `url`, `repo_url` or `path` column works too, as does a
JSONL file whose objects carry any of those keys.
"""

