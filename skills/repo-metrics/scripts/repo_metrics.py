def process_repo(spec: RepoSpec, cfg: argparse.Namespace, scc_bin: str,
                 jscpd_cmd: Optional[List[str]], dup_engine: str,
                 tokens: Dict[str, str], out_dir: Path) -> Dict[str, Any]:
    started = time.time()
    artifact = out_dir / "artifacts" / f"{spec.name}.json"
    row: Dict[str, Any] = {
        "repo": spec.full_name,
        "platform": spec.platform,
        "source": spec.raw,
        "status": "ok",
        "error": "",
        "duplication_engine": dup_engine,
    }

    clone_path = None
    cloned_fresh = False
    try:
        clone_path, note = ensure_clone(
            spec, Path(cfg.clones_dir), tokens, cfg.clone_timeout, not cfg.full_clone,
            cfg.allow_non_git, cfg.branch_mode in ("latest", "largest"),
        )
        if clone_path is None:
            raise RuntimeError(note)
        cloned_fresh = note == "cloned"
        has_git = note != "non-git source tree"
        row["source_kind"] = "git" if has_git else "source-export"

        branch = ""
        if has_git:
            branch, default = resolve_branch(clone_path, cfg.branch_mode)
            row["analysis_branch"] = branch
            row["default_branch"] = default
            if cfg.branch_mode in ("latest", "largest") and branch != default:
                run(["git", "checkout", "--force", branch], clone_path, 600)

        row.update(collect_loc(scc_bin, clone_path, cfg.exclude_dirs, cfg.scc_timeout,
                               cfg.data_languages))

        if jscpd_cmd:
            try:
                row.update(jscpd_ratio(
                    jscpd_cmd, clone_path, out_dir / "jscpd" / spec.name,
                    cfg.exclude_dirs, cfg.min_tokens, cfg.min_lines, cfg.jscpd_timeout,
                    not cfg.no_gitignore,
                ))
            except Exception as exc:  # noqa: BLE001 - fall back rather than lose the repo
                row.update(builtin_dup_ratio(clone_path, cfg.exclude_dirs, cfg.min_tokens,
                                             cfg.min_lines, cfg.dup_file_limit))
                row["duplication_engine"] = "builtin-fallback"
                row["error"] = f"jscpd fell back: {exc}"
        else:
            row.update(builtin_dup_ratio(clone_path, cfg.exclude_dirs, cfg.min_tokens,
                                         cfg.min_lines, cfg.dup_file_limit))

        if has_git:
            row.update(non_merge_commits(clone_path, branch, cfg.git_timeout))
        else:
            # Blank, not 0 — there is no history to count, which is different
            # from a repository that genuinely has no commits.
            row.update({
                "non_merge_commits": "", "non_merge_commits_raw": "",
                "revert_commits_excluded": "", "contributors": "",
                "first_commit": "", "last_commit": "",
            })
        row.update(collect_build_test(clone_path, cfg.build_check, cfg.build_timeout,
                                      str(row.get("primary_code_language") or "")))

    except Exception as exc:  # noqa: BLE001 - record and continue with the next repo
        row["status"] = "error"
        row["error"] = redact(f"{type(exc).__name__}: {exc}", tokens)
        if cfg.traceback:
            log(traceback.format_exc())
    finally:
        if cfg.delete_clones and cloned_fresh and clone_path and not spec.local_path:
            shutil.rmtree(clone_path, ignore_errors=True)

    row["measurement_seconds"] = round(time.time() - started, 1)
    artifact.parent.mkdir(parents=True, exist_ok=True)
    artifact.write_text(json.dumps(row, indent=2, default=str), encoding="utf-8")
    return row


# ── output ───────────────────────────────────────────────────────────────────

def write_outputs(rows: List[Dict[str, Any]], out_dir: Path) -> None:
    rows = sorted(rows, key=lambda r: str(r.get("repo") or ""))
    csv_path = out_dir / "repo_metrics.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=CSV_COLUMNS, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow({key: row.get(key, "") for key in CSV_COLUMNS})

    with (out_dir / "repo_metrics.jsonl").open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, default=str) + "\n")

    ok = [r for r in rows if r.get("status") == "ok"]
    failed = [r for r in rows if r.get("status") != "ok"]
    engines = Counter(r.get("duplication_engine") for r in ok)
    statuses = Counter(r.get("build_test_status") for r in ok)
    summary = {
        "repos_total": len(rows),
        "repos_ok": len(ok),
        "repos_failed": len(failed),
        "logical_loc_total": sum(int(r.get("logical_loc") or 0) for r in ok),
        "non_authored_loc_total": sum(int(r.get("non_authored_loc") or 0) for r in ok),
        "duplication_ratio_mean": round(
            sum(float(r.get("duplication_ratio") or 0) for r in ok) / len(ok), 4) if ok else 0.0,
        "non_merge_commits_total": sum(int(r.get("non_merge_commits") or 0) for r in ok),
        "duplication_engines": dict(engines),
        "build_test_status_counts": dict(statuses),
        "failures": [{"repo": r.get("repo"), "error": r.get("error")} for r in failed],
    }
    (out_dir / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")

    log(f"wrote {csv_path}")
    log(f"ok={len(ok)} failed={len(failed)} "
        f"logical_loc={summary['logical_loc_total']:,} "
        f"non_authored_loc={summary['non_authored_loc_total']:,}")


# ── cli ──────────────────────────────────────────────────────────────────────

def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--repos", required=True, type=Path,
                        help="file listing repos (txt/csv/json/jsonl)")
    parser.add_argument("--out", required=True, type=Path, help="output directory")
    parser.add_argument("--clones-dir", default=default_clones_dir(),
                        help="where remote repos are cloned (env: DATALABS_CLONES_DIR)")
    parser.add_argument("--tokens-file", type=Path, default=default_tokens_file(),
                        help="key=value file with GitHub/GitLab tokens (env: DATALABS_TOKENS)")
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--limit", type=int, default=0, help="process at most N repos")
    parser.add_argument("--branch-mode", choices=["default", "latest", "largest"], default="default")
    parser.add_argument("--default-platform", choices=["github", "gitlab"], default="github",
                        help="platform assumed for bare owner/repo lines")
    parser.add_argument("--gitlab-host", default="gitlab.com",
                        help="host used for bare gitlab paths, e.g. gitlab.mycorp.com")
    parser.add_argument("--build-check", choices=["none", "detect", "docker"], default="detect",
                        help="detect = static build/runtime identification; docker = real build+test attempt")
    parser.add_argument("--exclude-dirs", default=",".join(DEFAULT_EXCLUDE_DIRS))
    parser.add_argument("--data-languages", default=",".join(sorted(DATA_LANGUAGES)),
                        help="languages treated as data when deriving code_loc; "
                             "logical_loc is never affected")
    parser.add_argument("--wide-exclude", action="store_true",
                        help="also exclude third_party, Pods, target, .next and similar")
    parser.add_argument("--min-tokens", type=int, default=50)
    parser.add_argument("--min-lines", type=int, default=5)
    parser.add_argument("--dup-file-limit", type=int, default=8000,
                        help="max files scanned by the built-in duplication fallback")
    parser.add_argument("--no-jscpd", action="store_true",
                        help="skip jscpd and always use the built-in detector")
    parser.add_argument("--no-gitignore", action="store_true",
                        help="let the duplication scan see gitignored files (scc never does)")
    parser.add_argument("--allow-non-git", action="store_true",
                        help="measure source trees with no git history; commit "
                             "metrics are left blank rather than reported as zero")
    parser.add_argument("--full-clone", action="store_true",
                        help="disable --filter=blob:none partial clones")
    parser.add_argument("--delete-clones", action="store_true",
                        help="remove freshly cloned repos after measuring")
    parser.add_argument("--force", action="store_true",
                        help="re-measure repos that already have an artifact")
    parser.add_argument("--clone-timeout", type=int, default=1800)
    parser.add_argument("--scc-timeout", type=int, default=900)
    parser.add_argument("--jscpd-timeout", type=int, default=1800)
    parser.add_argument("--git-timeout", type=int, default=900)
    parser.add_argument("--build-timeout", type=int, default=2400)
    parser.add_argument("--traceback", action="store_true")
    return parser


def main(argv: Optional[List[str]] = None) -> int:
    cfg = build_parser().parse_args(argv)

    cfg.exclude_dirs = [d.strip() for d in cfg.exclude_dirs.split(",") if d.strip()]
    cfg.data_languages = [d.strip() for d in cfg.data_languages.split(",") if d.strip()]
    if cfg.wide_exclude:
        cfg.exclude_dirs = list(dict.fromkeys(cfg.exclude_dirs + WIDE_EXTRA_EXCLUDE_DIRS))

    scc_bin = find_scc()
    if not scc_bin:
        log("ERROR: scc not found. Set SCC_BIN, or place it at .tools/bin/scc, or brew install scc")
        return 2

    jscpd_cmd: Optional[List[str]] = None
    dup_engine = "builtin-fallback"
    if not cfg.no_jscpd:
        jscpd_cmd, dup_engine = find_jscpd()
    if jscpd_cmd is None and not cfg.no_jscpd:
        log("WARNING: jscpd not found (needs Node). Falling back to the built-in detector; "
            "rows will be labelled duplication_engine=builtin-fallback and are NOT jscpd numbers.")

    if cfg.build_check == "docker" and not docker_available():
        log("WARNING: docker daemon unreachable — downgrading --build-check to detect")
        cfg.build_check = "detect"

    specs = load_repo_list(cfg.repos, cfg.default_platform, cfg.gitlab_host)
    if cfg.limit:
        specs = specs[:cfg.limit]
    if not specs:
        log(f"ERROR: no usable repo entries in {cfg.repos}")
        return 2

    out_dir: Path = resolve_out(cfg.out)
    (out_dir / "artifacts").mkdir(parents=True, exist_ok=True)
    Path(cfg.clones_dir).mkdir(parents=True, exist_ok=True)
    tokens = load_tokens(cfg.tokens_file)

    rows: List[Dict[str, Any]] = []
    pending: List[RepoSpec] = []
    for spec in specs:
        artifact = out_dir / "artifacts" / f"{spec.name}.json"
        if artifact.is_file() and not cfg.force:
            try:
                rows.append(json.loads(artifact.read_text(encoding="utf-8")))
                continue
            except json.JSONDecodeError:
                pass
        pending.append(spec)

    log(f"{len(specs)} repos | {len(rows)} cached | {len(pending)} to measure | "
        f"scc={scc_bin} duplication={dup_engine} build-check={cfg.build_check} "
        f"workers={cfg.workers}")

    done = 0
    with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, cfg.workers)) as pool:
        futures = {
            pool.submit(process_repo, spec, cfg, scc_bin, jscpd_cmd, dup_engine, tokens, out_dir): spec
            for spec in pending
        }
        for future in concurrent.futures.as_completed(futures):
            spec = futures[future]
            done += 1
            try:
                row = future.result()
            except Exception as exc:  # noqa: BLE001 - never lose the whole run
                row = {"repo": spec.full_name, "platform": spec.platform, "source": spec.raw,
                       "status": "error", "error": f"{type(exc).__name__}: {exc}"}
            rows.append(row)
            flag = "OK " if row.get("status") == "ok" else "ERR"
            log(f"[{done}/{len(pending)}] {flag} {row.get('repo')} "
                f"loc={row.get('logical_loc', '-')} dup={row.get('duplication_ratio', '-')} "
                f"commits={row.get('non_merge_commits', '-')} "
                f"({row.get('measurement_seconds', '?')}s)")
            write_outputs(rows, out_dir)

    write_outputs(rows, out_dir)
    return 0


if __name__ == "__main__":
    sys.exit(main())
